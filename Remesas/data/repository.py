"""Única abstracción de acceso a datos de la aplicación."""
from __future__ import annotations

from contextlib import AbstractContextManager
from typing import Any, Iterable, Protocol, runtime_checkable


@runtime_checkable
class IDataRepository(Protocol):
    """Contrato común para lecturas, escrituras y transacciones PostgreSQL."""

    def execute(self, query: str, params: Iterable[Any] | None = None): ...
    def executemany(self, query: str, params: Iterable[Iterable[Any]]): ...
    def transaction(self) -> AbstractContextManager["IDataRepository"]: ...
    def connect(self) -> AbstractContextManager["IDataRepository"]: ...
    def commit(self) -> None: ...
    def rollback(self) -> None: ...
    def close(self) -> None: ...

